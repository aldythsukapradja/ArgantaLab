  const [, setTick] = useState(0) // cheap re-render trigger for inspector/layers/objlist after ref mutations

  function markDirty() { setRev((r) => ({ ...r, [activeId]: (r[activeId] || 1) + 1 })); setTick((t) => (t + 1) & 0xffff) }

  // ---------- canvas geometry ----------
  function w2s(wx: number, wy: number) { const c = camRef.current; return { x: wx * c.zoom - c.x, y: wy * c.zoom - c.y } }
  function s2w(sx: number, sy: number) { const c = camRef.current; return { x: (sx + c.x) / c.zoom, y: (sy + c.y) / c.zoom } }
  function s2tile(sx: number, sy: number) { const w = s2w(sx, sy); return { tx: Math.floor(w.x / TP), ty: Math.floor(w.y / TP) } }
  function fit() {
    if (!map || !stageRef.current) return
    const r = stageRef.current.getBoundingClientRect()
    const mw = map.W * TP, mh = map.H * TP
    const z = Math.min(r.width / mw, r.height / mh) * 0.92
    camRef.current = { zoom: z, x: (mw * z - r.width) / 2, y: (mh * z - r.height) / 2 }
  }
  function resizeCanvas() {
    const canvas = canvasRef.current, wrap = stageRef.current
    if (!canvas || !wrap) return
    const dpr = Math.min(2, window.devicePixelRatio || 1)
    const r = wrap.getBoundingClientRect()
    canvas.width = Math.max(1, Math.floor(r.width * dpr)); canvas.height = Math.max(1, Math.floor(r.height * dpr))
    canvas.style.width = r.width + 'px'; canvas.style.height = r.height + 'px'
    draw()
  }

  const imgCacheRef = useRef<Record<string, HTMLImageElement>>({})
  function getImg(src: string): HTMLImageElement | null {
    if (!src) return null
    let img = imgCacheRef.current[src]
    if (!img) { img = new Image(); img.src = src; imgCacheRef.current[src] = img }
    return img.complete && img.naturalWidth ? img : null
  }

  function objColor(o: Obj) { return o.color || '#8b7dff' }
  function shade(hex: string, p: number) {
    const n = parseInt(hex.slice(1), 16); let r = (n >> 16) & 255, g = (n >> 8) & 255, b = n & 255
    r = Math.round(r + (p < 0 ? r * p : (255 - r) * p)); g = Math.round(g + (p < 0 ? g * p : (255 - g) * p)); b = Math.round(b + (p < 0 ? b * p : (255 - b) * p))
    return `rgb(${r},${g},${b})`
  }
  function roundRect(ctx: CanvasRenderingContext2D, x: number, y: number, w: number, h: number, r: number) {
    ctx.beginPath(); ctx.moveTo(x + r, y); ctx.arcTo(x + w, y, x + w, y + h, r); ctx.arcTo(x + w, y + h, x, y + h, r)
    ctx.arcTo(x, y + h, x, y, r); ctx.arcTo(x, y, x + w, y, r); ctx.closePath()
  }

  // draw() is parametrized so it can also render into an offscreen canvas at
  // scale=1 for the HTML export snapshot (§ export). With no `target`, it
  // draws the live viewport exactly as before.
  function draw(target?: { ctx: CanvasRenderingContext2D; vw: number; vh: number; clean?: boolean }) {
    const canvas = canvasRef.current, m = map
    if ((!canvas && !target) || !m) return
    const ctx = target?.ctx ?? canvas!.getContext('2d')!
    const dpr = target ? 1 : Math.min(2, window.devicePixelRatio || 1)
    if (!target) ctx.setTransform(dpr, 0, 0, dpr, 0, 0)
    const vw = target?.vw ?? stageRef.current!.getBoundingClientRect().width
    const vh = target?.vh ?? stageRef.current!.getBoundingClientRect().height
    ctx.clearRect(0, 0, vw, vh)
    const cam = camRef.current
    const mw = m.W * TP, mh = m.H * TP
    const tl = w2s(0, 0), br = w2s(mw, mh)

    if (layerVis.current.base || target?.clean) {
      const img = getImg(m.image)
      if (img) ctx.drawImage(img, tl.x, tl.y, br.x - tl.x, br.y - tl.y)
      else { ctx.fillStyle = '#6fae5a'; ctx.fillRect(tl.x, tl.y, br.x - tl.x, br.y - tl.y) }
      ctx.strokeStyle = '#3d6b34'; ctx.lineWidth = 2; ctx.strokeRect(tl.x, tl.y, br.x - tl.x, br.y - tl.y)
    }
    if (layerVis.current.zones || target?.clean) for (const z of m.zones) {
      const a = w2s(z.x * TP, z.y * TP)
      ctx.fillStyle = z.c + 'b3'; roundRect(ctx, a.x, a.y, z.w * TP * cam.zoom, z.h * TP * cam.zoom, 8 * cam.zoom); ctx.fill()
      const isSel = selRef.current?.kind === 'zone' && selRef.current.zone === z
      ctx.strokeStyle = isSel ? '#fff' : '#0004'; ctx.lineWidth = isSel ? 3 : 1; ctx.stroke()
      if (cam.zoom > 0.5 || target?.clean) { ctx.fillStyle = '#fff'; ctx.font = `700 ${Math.min(14, 10 * cam.zoom)}px system-ui,sans-serif`; ctx.textAlign = 'left'; ctx.textBaseline = 'top'; ctx.fillText(z.l, a.x + 6, a.y + 5) }
    }
    if (!target?.clean) {
      const zd = zoneDraftRef.current
      if (zd) {
        const x0 = Math.min(zd.x0, zd.x1), y0 = Math.min(zd.y0, zd.y1), x1 = Math.max(zd.x0, zd.x1), y1 = Math.max(zd.y0, zd.y1)
        const a = w2s(x0 * TP, y0 * TP)
        ctx.fillStyle = '#ffffff33'; ctx.fillRect(a.x, a.y, (x1 - x0 + 1) * TP * cam.zoom, (y1 - y0 + 1) * TP * cam.zoom)
        ctx.strokeStyle = '#fff'; ctx.setLineDash([5, 4]); ctx.lineWidth = 2; ctx.strokeRect(a.x, a.y, (x1 - x0 + 1) * TP * cam.zoom, (y1 - y0 + 1) * TP * cam.zoom); ctx.setLineDash([])
      }
    }
    if (layerVis.current.collision || target?.clean) {
      const regions = collision.current[activeId] || []
      for (const region of regions) {
        const isSel = selRef.current?.kind === 'boundary' && selRef.current.region === region
        for (const k of region.tiles) {
          const [x, y] = k.split(',').map(Number); const a = w2s(x * TP, y * TP)
          ctx.fillStyle = '#e5533d55'; ctx.fillRect(a.x, a.y, TP * cam.zoom, TP * cam.zoom)
          ctx.strokeStyle = isSel ? '#fff' : '#e5533d'; ctx.lineWidth = isSel ? 2 : 1; ctx.strokeRect(a.x, a.y, TP * cam.zoom, TP * cam.zoom)
        }
      }
    }
    if ((layerVis.current.grid && !target?.clean) && cam.zoom > 0.28) {
      ctx.lineWidth = 1
      for (let x = 0; x <= m.W; x++) { const s = w2s(x * TP, 0), e = w2s(x * TP, mh); ctx.strokeStyle = x % 5 === 0 ? '#ffffff40' : '#ffffff18'; ctx.beginPath(); ctx.moveTo(s.x, s.y); ctx.lineTo(e.x, e.y); ctx.stroke() }
      for (let y = 0; y <= m.H; y++) { const s = w2s(0, y * TP), e = w2s(mw, y * TP); ctx.strokeStyle = y % 5 === 0 ? '#ffffff40' : '#ffffff18'; ctx.beginPath(); ctx.moveTo(s.x, s.y); ctx.lineTo(e.x, e.y); ctx.stroke() }
    }
    if (!target?.clean && hoverRef.current && cam.zoom > 0.28) {
      const hv = hoverRef.current
      const rad = tool === 'collision' ? brushRef.current.size : 1
      const off = Math.floor(rad / 2)
      const hOff = w2s((hv.tx - off) * TP, (hv.ty - off) * TP)
      ctx.fillStyle = '#fff2'; ctx.fillRect(hOff.x, hOff.y, rad * TP * cam.zoom, rad * TP * cam.zoom)
      const hA = w2s(hv.tx * TP, hv.ty * TP)
      ctx.strokeStyle = '#fff'; ctx.lineWidth = 1.5; ctx.strokeRect(hA.x, hA.y, TP * cam.zoom, TP * cam.zoom)
    }
    if (layerVis.current.sprites || target?.clean) for (const o of m.objects.filter((o) => o.kind === 'sprite')) drawMarker(ctx, o, true, cam)
    if (layerVis.current.objects || target?.clean) for (const o of m.objects.filter((o) => o.kind !== 'sprite')) drawMarker(ctx, o, false, cam)

    if (!target?.clean) {
      const mr = measureRef.current
      if (mr.a) {
        const a = w2s((mr.a.tx + 0.5) * TP, (mr.a.ty + 0.5) * TP)
        ctx.beginPath(); ctx.arc(a.x, a.y, 5, 0, 7); ctx.fillStyle = '#fff'; ctx.fill(); ctx.strokeStyle = '#000a'; ctx.stroke()
        const b2 = mr.b || hoverRef.current
        if (b2) {
          const b = w2s((b2.tx + 0.5) * TP, (b2.ty + 0.5) * TP)
          ctx.setLineDash([6, 4]); ctx.strokeStyle = '#fff'; ctx.lineWidth = 2; ctx.beginPath(); ctx.moveTo(a.x, a.y); ctx.lineTo(b.x, b.y); ctx.stroke(); ctx.setLineDash([])
          const dist = Math.hypot(mr.a.tx - b2.tx, mr.a.ty - b2.ty).toFixed(1)
          const mx = (a.x + b.x) / 2, my = (a.y + b.y) / 2
          ctx.font = '700 11px system-ui,sans-serif'; const tw = ctx.measureText(dist + ' tiles').width
          ctx.fillStyle = '#0b0d1cd0'; roundRect(ctx, mx - tw / 2 - 6, my - 18, tw + 12, 17, 8); ctx.fill()
          ctx.fillStyle = '#fff'; ctx.textAlign = 'center'; ctx.fillText(dist + ' tiles', mx, my - 6); ctx.textAlign = 'start'
        }
      }
    }
  }

  function drawMarker(ctx: CanvasRenderingContext2D, o: Obj, isSprite: boolean, cam: { zoom: number }) {
    const c = w2s((o.x + (o.w ? o.w / 2 : 0.5)) * TP, (o.y + (o.h ? o.h / 2 : 0.5)) * TP)
    const R = isSprite ? Math.max(9, TP * cam.zoom * 0.38) : Math.max(11, (o.hitR || 1) * TP * cam.zoom * 0.55)
    const col = objColor(o), isSel = selRef.current?.kind === 'object' && selRef.current.obj === o
    if (!isSprite) { ctx.beginPath(); ctx.arc(c.x, c.y, (o.hitR || 1) * TP * cam.zoom, 0, 7); ctx.fillStyle = col + '1e'; ctx.fill() }
    ctx.beginPath(); ctx.ellipse(c.x, c.y + R * 0.8, R * 0.7, R * 0.28, 0, 0, 7); ctx.fillStyle = '#0004'; ctx.fill()
    const grad = ctx.createRadialGradient(c.x - R * 0.35, c.y - R * 0.4, R * 0.2, c.x, c.y, R)
    grad.addColorStop(0, '#ffffffcc'); grad.addColorStop(0.32, col); grad.addColorStop(1, shade(col, -0.4))
    ctx.beginPath(); ctx.arc(c.x, c.y, R, 0, 7); ctx.fillStyle = grad; ctx.fill()
    ctx.lineWidth = isSel ? 3 : 1.4; ctx.strokeStyle = isSel ? '#fff' : shade(col, -0.25); ctx.stroke()
    if (isSel) { ctx.beginPath(); ctx.arc(c.x, c.y, R + 4, 0, 7); ctx.strokeStyle = '#6366f1'; ctx.lineWidth = 2; ctx.stroke() }
    ctx.font = `${R}px system-ui,sans-serif`; ctx.textAlign = 'center'; ctx.textBaseline = 'middle'; ctx.fillText(o.icon || '◆', c.x, c.y + R * 0.05)
    if (!isSprite && cam.zoom > 0.55) {
      const label = o.name || o.id
      ctx.font = '700 10px system-ui,sans-serif'; const tw = ctx.measureText(label).width
      ctx.fillStyle = '#0b0d1cd0'; roundRect(ctx, c.x - tw / 2 - 5, c.y + R + 3, tw + 10, 15, 7); ctx.fill()
      ctx.fillStyle = '#fff'; ctx.fillText(label, c.x, c.y + R + 10)
    }
    if (o.note) { ctx.beginPath(); ctx.arc(c.x + R * 0.7, c.y - R * 0.7, 5, 0, 7); ctx.fillStyle = '#d97706'; ctx.fill() }
    if (o.asset?.status === 'needs-art') {
      ctx.beginPath(); ctx.arc(c.x - R * 0.7, c.y - R * 0.7, 5, 0, 7); ctx.fillStyle = '#8b5cf6'; ctx.fill()
      ctx.fillStyle = '#fff'; ctx.font = '900 8px system-ui'; ctx.fillText('?', c.x - R * 0.7, c.y - R * 0.68)
    }
  }

  function pick(sx: number, sy: number): { kind: 'object'; obj: Obj } | { kind: 'zone'; zone: Zone } | null {
    if (!map) return null
    const cam = camRef.current
    for (let i = map.objects.length - 1; i >= 0; i--) {
      const o = map.objects[i]; const c = w2s((o.x + (o.w ? o.w / 2 : 0.5)) * TP, (o.y + (o.h ? o.h / 2 : 0.5)) * TP)
      const R = Math.max(11, (o.hitR || 1) * TP * cam.zoom * 0.55)
      if (Math.hypot(sx - c.x, sy - c.y) <= R + 4) return { kind: 'object', obj: o }
    }
    for (const z of map.zones) {
      const a = w2s(z.x * TP, z.y * TP)
      if (sx >= a.x && sx <= a.x + z.w * TP * cam.zoom && sy >= a.y && sy <= a.y + z.h * TP * cam.zoom) return { kind: 'zone', zone: z }
    }
    return null
  }

