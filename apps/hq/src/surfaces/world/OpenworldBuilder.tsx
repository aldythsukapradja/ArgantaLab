// ---------------- pixel-agent asset model ----------------
type AnimType = 'none' | 'idle-loop' | 'state-toggle' | 'walk' | 'one-shot'
type GenType = 'map-object' | 'character' | 'tileset' | 'none'
type ViewType = 'low top-down' | 'high top-down' | 'side'
type AssetSpec = {
  gen: GenType
  dirs: 1 | 4 | 8
  view: ViewType
  anim: AnimType
  loop?: string
  states?: string[]
  actions?: string[]
  prompt?: string
  status: 'has-art' | 'needs-art' | 'placeholder'
}
type Annot = { name?: string; desc?: string; intent?: string }

type Obj = Annot & {
  id: string; kind: string; x: number; y: number; w?: number; h?: number; hitR?: number
  icon?: string; color?: string; note?: string; subtype?: string
  asset?: AssetSpec
}
type Zone = Annot & {
  id: string; x: number; y: number; w: number; h: number; c: string; l: string
  role?: 'label' | 'terrain' | 'trigger'
  asset?: AssetSpec
}
type BoundaryRegion = Annot & { id: string; tiles: string[]; mode: 'block' | 'clear' }
type MapData = {
  id: string; name: string; sub: string; swatch: string; image: string
  W: number; H: number
  zones: Zone[]
  objects: Obj[]
  scene: string
}

