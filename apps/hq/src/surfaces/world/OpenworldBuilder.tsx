function iconForPlacement(key: string): string {
  const k = key.toLowerCase()
  if (k.includes('tree')) return '🌲'
  if (k.includes('flower')) return '🌸'
  if (k.includes('shop')) return '🏪'
  if (k.includes('ore') || k.includes('boulder')) return '⛏'
  if (k.includes('fountain')) return '⛲'
  if (k.includes('fish')) return '🎣'
  if (k.includes('trough')) return '🥣'
  if (k.includes('mushroom')) return '🍄'
  if (k.includes('bush')) return '🌿'
  if (k.includes('greenhouse')) return '🏡'
  if (k.includes('windmill')) return '🌬'
  if (k.includes('scarecrow')) return '🧑‍🌾'
  if (k.includes('wall') || k.includes('scoreboard') || k.includes('signpost')) return '🚩'
  return '📦'
}
function iconForHotspotKind(kind: string): string {
  return { shop: '🏪', sell: '💰', dungeon: '⚔', dock: '🎣', pvprank: '🏆', castle: '🏰' }[kind] || '📍'
}

// ---------- manifest -> per-map normalized MapData ----------
// Manifest-origin elements (real, already-shipped art) default asset.status
// to 'has-art' — they're excluded from the PIXEL ASSETS export automatically.
// Anything the operator places NEW (marker/zone/sprite/boundary) defaults to
// 'needs-art' via defaultAsset()'s own default.
function normalize(manifest: any): Record<string, MapData> {
  const out: Record<string, MapData> = {}
  for (const id of MAP_ORDER) {
    const m = manifest?.maps?.[id]
    const meta = MAP_META[id]
    if (!m) { out[id] = { id, name: meta.name, sub: meta.sub, swatch: meta.swatch, image: '', W: 60, H: 48, zones: [], objects: [], scene: MAP_SCENE[id] || '' }; continue }
    const zones: Zone[] = []
    const objects: Obj[] = []

    if (id === 'kingdom') {
      let zi = 0
      for (const [key, r] of Object.entries<any>(m.zones || {})) {
        zones.push({ id: key, x: r.x0, y: r.y0, w: r.x1 - r.x0 + 1, h: r.y1 - r.y0 + 1, c: ZONE_COLORS[zi++ % ZONE_COLORS.length], l: key, role: 'label' })
      }
      for (const b of m.buildings || []) objects.push({ id: b.key, kind: 'building', x: b.tx, y: b.ty, w: b.w, h: b.h, icon: '🏠', color: '#8b7dff', asset: defaultAsset('building', 'has-art') })
      for (const p of m.placements || []) objects.push({ id: p.key + '@' + p.tx + ',' + p.ty, kind: 'placement', x: p.tx, y: p.ty, w: p.w, h: p.h, icon: iconForPlacement(p.key), color: '#8fae7a', asset: defaultAsset('placement', 'has-art') })
      for (const h of m.hotspots || []) {
        if (h.kind === 'realm') continue
        const cx = Math.round((h.rect.x0 + h.rect.x1) / 2), cy = Math.round((h.rect.y0 + h.rect.y1) / 2)
        objects.push({ id: h.id, kind: h.kind, x: cx, y: cy, hitR: Math.max(1, (h.rect.x1 - h.rect.x0 + 1) / 2), icon: iconForHotspotKind(h.kind), color: h.ported === false ? '#e5533d' : '#3fd07a', note: h.ported === false ? 'not wired yet' : undefined, asset: defaultAsset(h.kind, 'has-art') })
      }
      for (const p of m.portals || []) {
        const r = p.hqHotspot
        const cx = Math.round((r.x0 + r.x1) / 2), cy = Math.round((r.y0 + r.y1) / 2)
        objects.push({ id: p.id, kind: 'portal', x: cx, y: cy, hitR: 1.6, icon: PORTAL_ICON[p.id] || '📍', color: p.color, asset: defaultAsset('portal', 'has-art') })
      }
      for (const o of m.harvestNodes?.ore || []) objects.push({ id: `ore@${o.x},${o.y}`, kind: 'ore', x: o.x, y: o.y, icon: '⛏', color: '#c9a24a', asset: defaultAsset('ore', 'has-art') })
      for (const t of m.harvestNodes?.trees || []) objects.push({ id: `tree@${t.x},${t.y}`, kind: 'tree', x: t.x, y: t.y, icon: t.hard ? '🌳' : '🌲', color: '#4a8f4f', asset: defaultAsset('tree', 'has-art') })
    } else {
      for (const o of m.objects || []) {
        objects.push({ id: o.id, kind: o.kind, x: o.tile[0], y: o.tile[1], w: o.size?.[0], h: o.size?.[1], icon: o.icon || KIND_LABEL[o.kind]?.[0] || '◆', color: '#8b7dff', asset: defaultAsset(o.kind, 'has-art') })
      }
      if (id === 'bloomwall_pass' && Array.isArray(m.lane)) {
        m.lane.forEach(([x, y]: [number, number], i: number) => {
          objects.push({ id: `lane_${i}`, kind: 'sprite', x, y, icon: '·', color: '#cdb384', note: i === 0 ? 'lane start' : undefined, asset: defaultAsset('sprite', 'has-art') })
        })
      }
    }
    // m.image is already fully relative to public/farm-art/ — 'basemap.png'
    // for Kingdom, 'Worldmap/lashira-keep.png' etc. for realms.
    out[id] = { id, name: meta.name, sub: meta.sub, swatch: meta.swatch, image: m.image ? `/farm-art/${m.image}` : '', W: (m.grid?.[0]) || 60, H: (m.grid?.[1]) || 48, zones, objects, scene: MAP_SCENE[id] || '' }
  }
  return out
}

