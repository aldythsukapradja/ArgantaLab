// Small reusable chip-list editor (States / Actions) — a top-level component
// so its own useState survives parent re-renders.
function ChipEditor({ label, items, onChange }: { label: string; items: string[]; onChange: (v: string[]) => void }) {
  const [draft, setDraft] = useState('')
  return (
    <div className="owb-chipeditor">
      <label className="fl">{label}</label>
      <div className="chiprow">
        {items.map((it, i) => (
          <span key={it + i} className="chip removable" onClick={() => onChange(items.filter((_, j) => j !== i))}>{it} ✕</span>
        ))}
        {!items.length && <span className="chip-empty">none yet</span>}
      </div>
      <input
        className="owb-input sm" placeholder={`add ${label.toLowerCase()}, Enter`} value={draft}
        onChange={(e) => setDraft(e.target.value)}
        onKeyDown={(e) => { if (e.key === 'Enter' && draft.trim()) { onChange([...items, draft.trim()]); setDraft('') } }}
      />
    </div>
  )
}

