function defaultAsset(kind: string, status: AssetSpec['status'] = 'needs-art'): AssetSpec {
  const d = ASSET_DEFAULTS[kind] || { gen: 'map-object', dirs: 1, view: 'high top-down', anim: 'none' }
  return {
    gen: d.gen || 'map-object', dirs: d.dirs || 1, view: d.view || 'high top-down', anim: d.anim || 'none',
    loop: d.loop, states: d.states ? [...d.states] : undefined, actions: d.actions ? [...d.actions] : undefined, status,
  }
}
function animOptionsFor(kind: string): AnimType[] {
  if (kind === 'npc') return ['none', 'walk']
  if (kind === 'spawn') return ['none']
  return ['none', 'idle-loop', 'state-toggle', 'one-shot']
}
function ensureAsset(o: Obj | Zone, kind: string) { if (!o.asset) o.asset = defaultAsset(kind, 'needs-art') }

