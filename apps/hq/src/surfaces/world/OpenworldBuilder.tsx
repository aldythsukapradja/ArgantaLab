  // ---------- pointer interaction ----------
  // MUST be refs, not plain `let` locals: onPointerDown sets these then calls
  // forceRender() synchronously, which re-runs this component body before the
  // browser's next pointermove fires — a plain local would be reset to null
  // right there, so panning (and object drag) would set state and then
  // immediately discard it. Refs survive the re-render.
  const panStateRef = useRef<{ sx: number; sy: number; cx: number; cy: number } | null>(null)
  const dragObjRef = useRef<Obj | null>(null)

  function onPointerDown(e: React.PointerEvent<HTMLCanvasElement>) {
    if (!map) return
    const canvas = canvasRef.current!; canvas.setPointerCapture(e.pointerId)
    const rect = canvas.getBoundingClientRect(); const sx = e.clientX - rect.left, sy = e.clientY - rect.top
    const t = s2tile(sx, sy)
    if (tool === 'select') {
      const hit = pick(sx, sy)
      if (hit) { selRef.current = hit; dragObjRef.current = hit.kind === 'object' ? hit.obj : null; forceRender() }
      else { panStateRef.current = { sx: e.clientX, sy: e.clientY, cx: camRef.current.x, cy: camRef.current.y }; selRef.current = null; forceRender() }
    } else if (tool === 'marker') { addMarker(t.tx, t.ty) }
    else if (tool === 'zone' && !layerLock.current.zones) { zoneDraftRef.current = { x0: t.tx, y0: t.ty, x1: t.tx, y1: t.ty } }
    else if (tool === 'collision' && !layerLock.current.collision) { paintCollision(t.tx, t.ty) }
    else if (tool === 'sprite' && !layerLock.current.sprites) { stampSprite(t.tx, t.ty) }
    else if (tool === 'measure') {
      const mr = measureRef.current
      if (!mr.a || mr.b) { measureRef.current = { a: t, b: null } } else { measureRef.current = { a: mr.a, b: t } }
    }
  }
  function onPointerMove(e: React.PointerEvent<HTMLCanvasElement>) {
    const canvas = canvasRef.current; if (!canvas || !map) return
    const rect = canvas.getBoundingClientRect(); const sx = e.clientX - rect.left, sy = e.clientY - rect.top
    const t = s2tile(sx, sy); hoverRef.current = t
    if (dragObjRef.current) { dragObjRef.current.x = Math.max(0, Math.min(map.W - 1, t.tx)); dragObjRef.current.y = Math.max(0, Math.min(map.H - 1, t.ty)); markDirty() }
    else if (panStateRef.current) { const ps = panStateRef.current; camRef.current = { ...camRef.current, x: ps.cx - (e.clientX - ps.sx), y: ps.cy - (e.clientY - ps.sy) } }
    else if (zoneDraftRef.current) { zoneDraftRef.current.x1 = t.tx; zoneDraftRef.current.y1 = t.ty }
    else if (paintingRegionRef.current) { paintCollision(t.tx, t.ty) }
    // Unconditional: even plain hover (no drag/pan/paint) needs a re-render so
    // the "tile [x,y]" stagebar chip (read from hoverRef in JSX) stays live.
    forceRender()
  }
  function onPointerUp() {
    dragObjRef.current = null; panStateRef.current = null
    if (zoneDraftRef.current) { commitZone(); zoneDraftRef.current = null }
    if (paintingRegionRef.current) { selRef.current = { kind: 'boundary', region: paintingRegionRef.current }; paintingRegionRef.current = null }
    forceRender(); markDirty()
  }
  function onWheel(e: React.WheelEvent<HTMLCanvasElement>) {
    e.preventDefault()
    const canvas = canvasRef.current!; const rect = canvas.getBoundingClientRect()
    const sx = e.clientX - rect.left, sy = e.clientY - rect.top
    const before = s2w(sx, sy)
    const cam = camRef.current
    const nz = Math.max(0.25, Math.min(4, cam.zoom * (e.deltaY < 0 ? 1.12 : 0.89)))
    camRef.current = { ...cam, zoom: nz }
    const after = w2s(before.x, before.y)
    camRef.current = { zoom: nz, x: cam.x + (after.x - sx), y: cam.y + (after.y - sy) }
    forceRender()
  }

