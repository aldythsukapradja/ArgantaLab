// One-time: extract the COSMO <style> block from public/cosmo/index.html and scope
// every rule under html[data-ui="cosmo"] so it re-uses the founder's exact styles
// (1:1) without touching the classic UI. @keyframes/@font-face stay global so the
// polished animations are byte-identical. Run: node scripts/scope-cosmo-css.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const SCOPE = 'html[data-ui="cosmo"]';

const html = readFileSync(join(ROOT, 'public', 'cosmo', 'index.html'), 'utf8');
const css = html.split('<style>')[1].split('</style>')[0];

function scopeSelectorList(list) {
  return list.split(',').map((raw) => {
    let s = raw.trim(); if (!s) return raw;
    if (s === ':root') return SCOPE;
    if (s.startsWith(':root')) return SCOPE + s.slice(5);           // :root[data-theme=…], :root.x
    if (s === 'html') return SCOPE;
    if (s === 'body') return SCOPE + ' body';
    if (s.startsWith('html.dark')) return SCOPE + '.dark' + s.slice('html.dark'.length);
    if (s.startsWith('html ')) return SCOPE + s.slice('html'.length);
    if (s.startsWith('html,')) return SCOPE + s.slice('html'.length);
    if (s.startsWith('*')) return SCOPE + ' ' + s;                  // *{}, *::…
    if (s.startsWith('::')) return SCOPE + ' ' + s;                 // ::-webkit-scrollbar
    return SCOPE + ' ' + s;                                         // .foo, .a .b
  }).join(', ');
}

// brace-aware walk of the top level
let out = '', i = 0, n = css.length;
function readBlock(start) { // returns index after the matching close brace of the block that opens at `start`
  let depth = 0, j = start;
  for (; j < n; j++) { if (css[j] === '{') depth++; else if (css[j] === '}') { depth--; if (depth === 0) return j + 1; } }
  return n;
}
while (i < n) {
  // skip/emit whitespace + comments verbatim
  const ws = css.slice(i).match(/^(\s+|\/\*[\s\S]*?\*\/)/);
  if (ws) { out += ws[0]; i += ws[0].length; continue; }
  if (i >= n) break;
  // read up to the next '{'
  const brace = css.indexOf('{', i);
  if (brace === -1) { out += css.slice(i); break; }
  const prelude = css.slice(i, brace).trim();
  const end = readBlock(brace);
  const body = css.slice(brace + 1, end - 1);
  if (/^@(keyframes|-webkit-keyframes|font-face|page)/i.test(prelude)) {
    out += prelude + '{' + body + '}';                              // verbatim (animations, fonts)
  } else if (/^@(media|supports)/i.test(prelude)) {
    // scope each inner rule
    let inner = '', k = 0, m = body.length;
    while (k < m) {
      const iws = body.slice(k).match(/^(\s+|\/\*[\s\S]*?\*\/)/); if (iws) { inner += iws[0]; k += iws[0].length; continue; }
      const b2 = body.indexOf('{', k); if (b2 === -1) { inner += body.slice(k); break; }
      let d = 0, e = b2; for (; e < m; e++) { if (body[e] === '{') d++; else if (body[e] === '}') { d--; if (d === 0) { e++; break; } } }
      const sel = body.slice(k, b2).trim(); const inBody = body.slice(b2 + 1, e - 1);
      inner += (/^@/.test(sel) ? sel : scopeSelectorList(sel)) + '{' + inBody + '}';
      k = e;
    }
    out += prelude + '{' + inner + '}';
  } else {
    out += scopeSelectorList(prelude) + '{' + body + '}';
  }
  i = end;
}

const banner = `/* COSMO design system — extracted VERBATIM from the founder's COSMO_Final source\n   and scoped under ${SCOPE} (keyframes/fonts kept global for byte-identical\n   animations). Generated by scripts/scope-cosmo-css.mjs — do not hand-edit;\n   re-run after updating public/cosmo/index.html. */\n`;
writeFileSync(join(ROOT, 'src', 'cosmo', 'cosmo-system.css'), banner + out);
const rules = (out.match(/\{/g) || []).length;
console.log(`[scope] wrote src/cosmo/cosmo-system.css — ${rules} blocks, ${(out.length / 1024).toFixed(1)} KB, scoped under ${SCOPE}`);
