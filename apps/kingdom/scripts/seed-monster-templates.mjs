import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const kingdomRoot = path.resolve(__dirname, '..');

function normalizeSupabaseUrl(raw) {
  if (!raw) return null;
  const value = raw.trim().replace(/^['"]|['"]$/g, '');
  if (!value) return null;
  if (/^https?:\/\//i.test(value)) return value.replace(/\/$/, '');
  if (/\.supabase\.co$/i.test(value)) return `https://${value}`;
  if (/^[a-z0-9]{16,}$/i.test(value)) return `https://${value}.supabase.co`;
  return null;
}

function rarityForXp(xp) {
  if (xp >= 100000) return 'epic';
  if (xp >= 10000) return 'rare';
  if (xp >= 1000) return 'uncommon';
  return 'common';
}

function statFromXp(xp, min, max, scale) {
  return Math.max(min, Math.min(max, min + Math.round(Math.sqrt(Math.max(0, xp)) / scale)));
}

function sqlString(value) {
  if (value == null) return 'null';
  return `'${String(value).replaceAll("'", "''")}'`;
}

function sqlJson(value) {
  return `${sqlString(JSON.stringify(value))}::jsonb`;
}

async function loadJson(rel) {
  return JSON.parse(await fs.readFile(path.join(kingdomRoot, rel), 'utf8'));
}

async function upsertChunk(url, serviceKey, rows) {
  const res = await fetch(`${url}/rest/v1/kingdom_monster_templates?on_conflict=id`, {
    method: 'POST',
    headers: {
      apikey: serviceKey,
      Authorization: `Bearer ${serviceKey}`,
      'Content-Type': 'application/json',
      Prefer: 'resolution=merge-duplicates,return=minimal',
    },
    body: JSON.stringify(rows),
  });
  if (!res.ok) {
    throw new Error(`Supabase upsert failed ${res.status}: ${await res.text()}`);
  }
}

function rowsToSql(rows) {
  const header = [
    '-- Generated by apps/kingdom/scripts/seed-monster-templates.mjs --sql',
    '-- Run after apps/kingdom/supabase/002_kingdom_progression_presence.sql.',
    '',
    'begin;',
    '',
  ];
  const chunks = [];
  const chunkSize = 100;
  for (let i = 0; i < rows.length; i += chunkSize) {
    const values = rows.slice(i, i + chunkSize).map((r) => `  (${[
      sqlString(r.id),
      sqlString(r.name),
      Number(r.default_experience || 0),
      r.client_mob_id == null ? 'null' : Number(r.client_mob_id),
      r.client_palette_id == null ? 'null' : Number(r.client_palette_id),
      Number(r.base_hp || 100),
      Number(r.base_attack || 10),
      sqlString(r.rarity || 'common'),
      r.enabled ? 'true' : 'false',
      sqlJson(r.source_json || {}),
    ].join(', ')})`).join(',\n');

    chunks.push(`insert into public.kingdom_monster_templates
  (id, name, default_experience, client_mob_id, client_palette_id, base_hp, base_attack, rarity, enabled, source_json)
values
${values}
on conflict (id) do update set
  name = excluded.name,
  default_experience = excluded.default_experience,
  client_mob_id = excluded.client_mob_id,
  client_palette_id = excluded.client_palette_id,
  base_hp = excluded.base_hp,
  base_attack = excluded.base_attack,
  rarity = excluded.rarity,
  enabled = excluded.enabled,
  source_json = excluded.source_json;`);
  }
  return `${header.join('\n')}${chunks.join('\n\n')}\n\ncommit;\n`;
}

async function buildRows() {
  const [monsters, links] = await Promise.all([
    loadJson('data/core/monsters.json'),
    loadJson('data/links/monster-links.json'),
  ]);

  const monstersById = new Map(monsters.map((m) => [m.id, m]));
  const templates = new Map();

  for (const link of links) {
    if (!link?.monsterId || link.status === 'rejected' || templates.has(link.monsterId)) continue;
    const monster = monstersById.get(link.monsterId);
    if (!monster) continue;
    const xp = Number(monster.defaultExperience || 0);
    templates.set(link.monsterId, {
      id: monster.id,
      name: monster.name,
      default_experience: xp,
      client_mob_id: Number.isFinite(Number(link.mobId)) ? Number(link.mobId) : null,
      client_palette_id: Number.isFinite(Number(link.paletteId)) ? Number(link.paletteId) : null,
      base_hp: statFromXp(xp, 80, 2400, 1),
      base_attack: statFromXp(xp, 8, 320, 8),
      rarity: rarityForXp(xp),
      enabled: true,
      source_json: {
        monsterId: monster.id,
        slug: monster.slug,
        key: monster.key,
        defaultExperience: xp,
        tags: monster.tags || [],
        sourcePageUrls: monster.sourcePageUrls || [],
        link,
      },
    });
  }

  return [...templates.values()];
}

async function main() {
  const rows = await buildRows();

  if (process.argv.includes('--sql')) {
    const sql = rowsToSql(rows);
    const outIndex = process.argv.indexOf('--out');
    const outPath = outIndex >= 0 ? process.argv[outIndex + 1] : null;
    if (outPath) {
      await fs.writeFile(path.resolve(process.cwd(), outPath), sql, 'utf8');
      console.log(`Wrote ${rows.length} monster templates to ${outPath}`);
    } else {
      process.stdout.write(sql);
    }
    return;
  }

  const url = normalizeSupabaseUrl(process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL);
  const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY
    || process.env.SUPABASE_SERVICE_KEY
    || process.env.SUPABASE_SERVICE_ROLE;

  if (!url || !serviceKey) {
    console.error('Missing SUPABASE_URL/VITE_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY.');
    console.error('Run after applying apps/kingdom/supabase/002_kingdom_progression_presence.sql.');
    process.exit(1);
  }

  const chunkSize = 200;
  for (let i = 0; i < rows.length; i += chunkSize) {
    await upsertChunk(url, serviceKey, rows.slice(i, i + chunkSize));
    console.log(`Upserted ${Math.min(i + chunkSize, rows.length)} / ${rows.length}`);
  }

  console.log(`Done. Synced ${rows.length} Kingdom monster templates.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
