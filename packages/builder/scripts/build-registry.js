// B4b · Registry build script (Sonnet, mechanical — no design judgment).
// Parses every docs/arganta-core/blocks/<id>.html file's meta comment +
// <style>/markup/<script> sections into a PortableComponent entry
// (components.js, B1-frozen shape) and writes registry.js. Re-run with
// `npm run blocks:build` in this package whenever a block file changes.
//
// File anatomy contract (docs/arganta-core/blocks/README.md):
//   <!-- meta comment --> <style>…</style> <markup> [<script>…wiring IIFE…</script>]
// The markup may itself contain <script type="application/json" data-fill="…">
// seams — those stay part of `html`. Only a trailing, top-level, non-JSON
// <script> (the wiring IIFE) becomes the `javascript` field.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const BLOCKS_DIR = path.resolve(__dirname, '../../../docs/arganta-core/blocks');
const OUT_FILE = path.resolve(__dirname, '../src/registry.js');

function parseMeta(comment) {
  const meta = {};
  comment.split('\n').forEach((line) => {
    const m = line.match(/^\s*([a-zA-Z]+)\s*:\s*(.+?)\s*$/);
    if (!m) return;
    const key = m[1].trim();
    const val = m[2].trim();
    if (key === 'suitableFor') meta.suitableFor = val.split(',').map((s) => s.trim()).filter(Boolean);
    else if (key === 'tags') meta.tags = val.split(',').map((s) => s.trim()).filter(Boolean);
    else meta[key] = val;
  });
  return meta;
}

function parseBlockFile(file) {
  const raw = readFileSync(file, 'utf8');

  const commentMatch = raw.match(/^<!--([\s\S]*?)-->/);
  if (!commentMatch) throw new Error(`${file}: missing leading meta comment`);
  const meta = parseMeta(commentMatch[1]);
  let rest = raw.slice(commentMatch[0].length);

  const styleMatch = rest.match(/<style>([\s\S]*?)<\/style>/);
  if (!styleMatch) throw new Error(`${file}: missing <style> block`);
  const css = styleMatch[1].trim();
  rest = (rest.slice(0, styleMatch.index) + rest.slice(styleMatch.index + styleMatch[0].length)).trim();

  // The wiring script (if any) is the LAST top-level <script> tag with no
  // `type` attribute (JSON seams always carry type="application/json").
  let javascript;
  const scriptRe = /<script(?![^>]*type=)[^>]*>([\s\S]*?)<\/script>\s*$/;
  const scriptMatch = rest.match(scriptRe);
  if (scriptMatch) {
    javascript = scriptMatch[1].trim();
    rest = rest.slice(0, scriptMatch.index).trim();
  }

  const html = rest;

  return {
    id: meta.id,
    name: meta.name,
    category: meta.category,
    suitableFor: meta.suitableFor,
    description: meta.description,
    tags: meta.tags,
    html,
    css,
    ...(javascript ? { javascript } : {}),
  };
}

function main() {
  const files = readdirSync(BLOCKS_DIR)
    .filter((f) => f.endsWith('.html') && f !== 'preview.html')
    .sort();

  const components = files.map((f) => parseBlockFile(path.join(BLOCKS_DIR, f)));

  const body = components.map((c) => `  ${JSON.stringify(c, null, 2).replace(/\n/g, '\n  ')},`).join('\n');

  const out = `// ─────────────────────────────────────────────────────────────────────────
// B4b · Portable component registry (Sonnet, GENERATED — do not hand-edit)
// Generated by packages/builder/scripts/build-registry.js from
// docs/arganta-core/blocks/*.html. Re-run \`npm run blocks:build\` after
// changing a block file. Shape: components.js's PortableComponent (B1-frozen).
// ─────────────────────────────────────────────────────────────────────────

// AUTO-GENERATED-START
export const PORTABLE_REGISTRY = Object.freeze([
${body}
]);
// AUTO-GENERATED-END
`;

  writeFileSync(OUT_FILE, out);
  console.log(`Wrote ${components.length} components to ${path.relative(process.cwd(), OUT_FILE)}`);
}

main();
